#!/usr/bin/env python3
"""Build the G1 + two Sharpa Wave hands URDF (T06): the training G1 (rubber-hand URDF used by scheme D,
src/holosoma/holosoma/data/robots/g1/main_mesh_collision_rubberhand.urdf, read-only) with both <side>_rubber_hand_link
removed and <side>_hand_palm_joint re-parented to <side>_hand_flange of the Sharpa flange URDF at the mount of
system1/hand/sharpa.py (mount_transform). Every other G1 element is copied unchanged; mesh paths are rewritten relative
to the output file. A manifest records input sha256, the mount, masses and joint lists.

    hssim_s1/bin/python -B system1/hand/assemble.py --out system1/hand/assets/g1_29dof_sharpa.urdf
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from system1.hand.sharpa import SIDES, SharpaHand, mount_transform, sha256, urdf_path  # noqa: E402

G1_URDF = ROOT / "src/holosoma/holosoma/data/robots/g1/main_mesh_collision_rubberhand.urdf"


def urdf_mass(root: ET.Element) -> float:
    return sum(float(l.find("inertial/mass").get("value")) for l in root.findall("link") if l.find("inertial/mass") is not None)


def build(out: Path) -> dict:
    g1 = ET.parse(G1_URDF).getroot()
    rubber_mass = {s: float(g1.find(f"link[@name='{s}_rubber_hand_link']/inertial/mass").get("value")) for s in SIDES}
    base_mass = urdf_mass(g1)
    new = copy.deepcopy(g1)
    rel = lambda p: os.path.relpath(p, out.parent)  # noqa: E731
    for m in new.iter("mesh"):  # G1 meshes relative to the output
        m.set("filename", rel(G1_URDF.parent / m.get("filename")))
    info = {}
    for side in SIDES:
        link = new.find(f"link[@name='{side}_rubber_hand_link']")
        new.remove(link)
        j = new.find(f"joint[@name='{side}_hand_palm_joint']")
        hand = SharpaHand(side)
        M, minfo = mount_transform(side, hand)
        rpy = Rotation.from_matrix(M[:3, :3]).as_euler("xyz")  # URDF fixed-axis roll-pitch-yaw
        j.find("origin").set("xyz", " ".join(f"{v:.9g}" for v in M[:3, 3]))
        j.find("origin").set("rpy", " ".join(f"{v:.12g}" for v in rpy))
        j.find("child").set("link", hand.root)
        sh = ET.parse(urdf_path(side)).getroot()
        for el in list(sh):
            if el.tag not in ("link", "joint"):
                continue
            el = copy.deepcopy(el)
            for m in el.iter("mesh"):
                fn = m.get("filename").replace(f"package://{side}_sharpa_wave/", "")
                m.set("filename", rel(urdf_path(side).parent / fn))
            new.append(el)
        info[side] = dict(mount=minfo, mount_xyz=M[:3, 3].tolist(), mount_rpy=rpy.tolist(), sharpa_mass_kg=hand.mass,
                          rubber_hand_mass_kg=rubber_mass[side], finger_joints=hand.dof_names, sharpa_urdf_sha256=sha256(urdf_path(side)))
    out.parent.mkdir(parents=True, exist_ok=True)
    ET.indent(new, space="    ")
    out.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by system1/hand/assemble.py (T06); do not edit -->\n'
                   + ET.tostring(new, encoding="unicode") + "\n")
    tree = ET.parse(out).getroot()
    mov = [j.get("name") for j in tree.findall("joint") if j.get("type") in ("revolute", "continuous", "prismatic")]
    man = dict(output=str(out.relative_to(ROOT)) if out.is_relative_to(ROOT) else str(out), output_sha256=sha256(out),
               g1_source=str(G1_URDF.relative_to(ROOT)),
               g1_source_sha256=sha256(G1_URDF), mass_rubber_hand_robot_kg=base_mass, mass_sharpa_robot_kg=urdf_mass(tree),
               mass_difference_kg=urdf_mass(tree) - base_mass, movable_joints=len(mov),
               body_joints=[n for n in mov if not any(n.startswith(f"{s}_{f}") for s in SIDES for f in ("thumb", "index", "middle", "ring", "pinky"))],
               hands=info)
    if len(mov) != 29 + 44 or len(man["body_joints"]) != 29:
        raise ValueError(f"expected 29 body + 44 finger joints, got {len(mov)}")
    out.with_suffix(".manifest.json").write_text(json.dumps(man, indent=1))
    return man


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", type=Path, default=ROOT / "system1/hand/assets/g1_29dof_sharpa.urdf")
    a = p.parse_args()
    man = build(a.out.resolve())
    print(json.dumps({k: v for k, v in man.items() if k != "hands"}, indent=1))
    for s, v in man["hands"].items():
        print(s, json.dumps(v["mount"]), "rpy", np.round(v["mount_rpy"], 6).tolist())


if __name__ == "__main__":
    raise SystemExit(main())
