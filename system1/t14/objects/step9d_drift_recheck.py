#!/usr/bin/env python3
"""T14 step 9e side check: step 9d's partner support drift with the source mapped as the construction built the partner's legs.
Read only, CPU; step 9d's verdicts and files are not changed.

Step 9d (and 9c) judged role 1's support drift against the source solve played backwards over the whole clip
(step9_eval.py --r1-source reversed); the 9d partner's legs are reversed only inside the walking segment and are S copies at the
same frame in lift / put down. Here, for every evaluated 9d level: role 1's added drift (V0 quantity, round-6 windows, 0.01 m)
with --r1-source construction (gates r1_source of the same construction, regenerated by step9_gates.py into --gates-root), next
to the 9d value; whether the verdict of that level would change (other failed items unchanged).

    sonic_s1/bin/python -B system1/t14/objects/step9d_drift_recheck.py --gates-root logs_system1/t14/step9d_r1check --out <json> [--csv <csv>]
"""
import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
import shared_eval as se  # noqa: E402
import step8_rejudge as rj  # noqa: E402

L9D = ROOT / "logs_system1/t14/step9d"
SRC = [ROOT / "logs_system1/t14/step9b/src", ROOT / "logs_system1/t14/step9d/src"]


def main():
    import support
    from holosoma_retargeting.config_types.data_type import SMPLH_DEMO_JOINTS
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gates-root", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--csv", type=Path, default=None)
    a = ap.parse_args()
    fk = se.ctx()["fk"]
    names = list(SMPLH_DEMO_JOINTS)
    il, ir = names.index("L_Toe"), names.index("R_Toe")
    rows = []
    for clip in sorted(p.name for p in L9D.iterdir() if p.is_dir() and (p / "gates_m1p00.json").exists()):
        src = next(r / clip for r in SRC if (r / clip / "run_record.json").exists())
        srec = json.loads((src / "run_record.json").read_text())
        sq = np.load(src / f"{srec['tag']}_new_qpos.npz")["qpos"][:, :36].astype(np.float64)
        sfeet = se.feet(fk, sq)
        for lv in sorted(p for p in (L9D / clip).glob("m*p*") if (p / "eval.json").exists()):
            ev = json.loads((lv / "eval.json").read_text())
            g_old = json.loads((L9D / clip / f"gates_{lv.name}.json").read_text())
            g_new = json.loads((a.gates_root / clip / f"gates_{lv.name}.json").read_text())
            same = {k: g_new[k] for k in g_old} == g_old  # the regenerated gates equal 9d's apart from r1_source
            rec = json.loads((lv / "r1/run_record.json").read_text())
            z = np.load(lv / f"r1/{rec['tag']}_new_qpos.npz")
            q = z["qpos"][:, :36].astype(np.float64)
            T = len(q)
            flags = support.support_flags(z["human_joints"][:, [il, ir]])
            rf = se.feet(fk, q)
            rs = g_new["r1_source"]
            fr, R_, t_ = np.asarray(rs["frame"]), np.asarray(rs["R"]), np.asarray(rs["t"])
            vals_rev, vals_con = [], []
            for k, side in enumerate(("left", "right")):
                s0 = sfeet[f"{side}_foot_position_m"][:T]
                vals_rev.append(rj.added_drift(rf[f"{side}_foot_position_m"], s0[::-1], flags[:T, k])[0])
                vals_con.append(rj.added_drift(rf[f"{side}_foot_position_m"], np.einsum("tij,tj->ti", R_, s0[fr]) + t_, flags[:T, k])[0])
            mx = lambda v: max([x for x in v if x is not None], default=None)  # noqa: E731
            vr, vc = mx(vals_rev), mx(vals_con)
            old_failed = list(ev["failed"])
            new_failed = [x for x in old_failed if x != "V0 support drift r1"]
            if vc is not None and vc > rj.LIMIT + 1e-10:
                new_failed.append("V0 support drift r1")
            row = dict(clip=clip, level=lv.name, gates_identical_apart_from_r1_source=same, drift_r1_9d_m=ev["support_drift_round6"]["r1"]["value_m"],
                       drift_r1_reversed_recomputed_m=None if vr is None else round(vr, 5), drift_r1_construction_m=None if vc is None else round(vc, 5),
                       limit_m=rj.LIMIT, applicable_9d=ev["applicable"], failed_9d=" | ".join(old_failed),
                       applicable_with_construction_source=not new_failed, verdict_changes=(not new_failed) != ev["applicable"])
            rows.append(row)
            print(clip, lv.name, row["drift_r1_9d_m"], row["drift_r1_construction_m"], row["applicable_9d"], row["applicable_with_construction_source"], same, flush=True)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(json.dumps(dict(rules=__doc__, rows=rows, levels=len(rows), verdict_changes=sum(r["verdict_changes"] for r in rows),
                                     drift_r1_fails_with_construction=sum(1 for r in rows if (r["drift_r1_construction_m"] or 0) > rj.LIMIT)), indent=1) + "\n")
    if a.csv:
        with open(a.csv, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
